pub const LAT_TOP: f32 = 84.0;
pub const LAT_BOTTOM: f32 = -58.0;

/// Map position (0..1, 0..1) of a latitude/longitude.
pub fn project(lat: f32, lon: f32) -> (f32, f32) {
    ((lon + 180.0) / 360.0, (LAT_TOP - lat) / (LAT_TOP - LAT_BOTTOM))
}

/// Draw the land into a picture `w` pixels wide.
pub fn render(w: usize, land: Color32, sea: Color32) -> ColorImage {
    let h = (w as f32 * (LAT_TOP - LAT_BOTTOM) / 360.0) as usize;
    let mut img = ColorImage::new([w, h], sea);
    let mut polys: Vec<Poly> = vec![NORTH_AMERICA, SOUTH_AMERICA, EURASIA, AFRICA, AUSTRALIA];
    polys.extend_from_slice(ISLANDS);
    polys.extend_from_slice(WATER);
    // scanline fill, even-odd across all shapes
    let to_px = |lon: f32, lat: f32| {
        let (x, y) = project(lat, lon);
        (x * w as f32, y * h as f32)
    };
    let edges: Vec<((f32, f32), (f32, f32))> = polys
        .iter()
        .flat_map(|p| (0..p.len()).map(move |i| (p[i], p[(i + 1) % p.len()])))
        .map(|(a, b)| (to_px(a.0, a.1), to_px(b.0, b.1)))
        .collect();
    let mut xs: Vec<f32> = Vec::with_capacity(64);
    for row in 0..h {
        let y = row as f32 + 0.5;
        xs.clear();
        for ((x0, y0), (x1, y1)) in &edges {
            if (y >= *y0 && y < *y1) || (y >= *y1 && y < *y0) {
                xs.push(x0 + (y - y0) / (y1 - y0) * (x1 - x0));
            }
        }
        xs.sort_by(|a, b| a.total_cmp(b));
        for pair in xs.chunks(2) {
            if pair.len() < 2 {
                break;
            }
            let a = pair[0].max(0.0).round() as usize;
            let b = (pair[1].min(w as f32)).round() as usize;
            for x in a..b.min(w) {
                img.pixels[row * w + x] = land;
            }
        }
    }
    img
}
