/// Category for a host name (or "Other").
pub fn classify(name: Option<&str>, ip: std::net::Ipv4Addr) -> &'static str {
    if crate::sysnet::is_local(ip) {
        return "This network";
    }
    let Some(n) = name else { return "Other" };
    let n = n.to_lowercase();
    let n = n.trim_end_matches('.');
    for (suffix, cat) in RULES {
        if n == *suffix || n.ends_with(&format!(".{}", suffix)) {
            return cat;
        }
    }
    "Other"
}

pub fn describe(cat: &str) -> &'static str {
    match cat {
        "Advertising" => "Companies that show and measure ads.",
        "Analytics" => "Services that count how apps and websites are used (telemetry).",
        "Content delivery" => "Networks that deliver web pages, pictures and downloads quickly from nearby.",
        "Updates" => "Software and system update servers.",
        "Cloud" => "Big online services and data centers (Google, Microsoft, Amazon, Apple…).",
        "Social" => "Social networks and messaging.",
        "Streaming" => "Video and music streaming.",
        "Gaming" => "Game stores and online play.",
        "This network" => "Devices inside your home.",
        _ => "Not recognized yet.",
    }
}
